"""Copies Kat's full-body character art (for the social link and compendium pages) into the site.

Run: python3 tools/femc-profiles.py
Source: ~/Documents/UniverseHub-Images/Femc Mode Images/Compendium Profile Art/<Character>.jpg|png|webp
        (named after the character's id, e.g. Akihiko.jpg; ALIASES below covers files saved with random names)
Output: assets/femc/profile/<id>.webp (white or near-white backgrounds turned transparent, max 1400px tall)
        and assets/femc/profile/index.js listing who has one.
"""
import os, re, json
from collections import deque
from PIL import Image, ImageFilter

SRC = os.path.expanduser('~/Documents/UniverseHub-Images/Femc Mode Images/Compendium Profile Art')
DST = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'assets/femc/profile')
ALIASES = {
    '496e2dba76276478fa8e6a7508ebcafb': 'akihiko',
    '6707ba39d2939b71f74dddad39840d14': 'yukari',
    'shinjiart': 'shinjiro',
    'P5RAnnTakamaki': 'ann',
    'An_takamaki': None,          # the other Ann option, not used
}
# Keep only the top part of tall full-length art, so the figure isn't tiny on the page (fraction of the height).
CROP_TOP = {'ann': 0.625, 'mercy': 0.6, 'kiriko': 0.6, 'haechan': 0.6, 'haru': 0.56, 'kasumi': 0.6, 'astarion': 0.6, 'aphrodite': 0.6, 'shadowheart': 0.6, 'kuromi': 0.6, 'sebastian': 0.6, 'cloud': 0.6, 'judy': 0.6, 'noctis': 0.6, 'leon': 0.6}


def cut_background(im):
    """Flood-fills the near-white background in from the edges and makes it transparent, with a soft edge."""
    im = im.convert('RGBA')
    w, h = im.size
    px = im.load()
    if any(px[x, y][3] < 250 for x, y in ((0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1))):
        return im  # already has transparency
    white = lambda p: p[0] > 238 and p[1] > 238 and p[2] > 238
    bg = Image.new('L', (w, h), 0)
    m = bg.load()
    q = deque((x, y) for x in range(w) for y in (0, h - 1)) + deque((x, y) for y in range(h) for x in (0, w - 1))
    while q:
        x, y = q.popleft()
        if m[x, y] or not white(px[x, y]):
            continue
        m[x, y] = 255
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < w and 0 <= ny < h and not m[nx, ny]:
                q.append((nx, ny))
    alpha = bg.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.GaussianBlur(1.2)).point(lambda v: 255 - v)
    im.putalpha(alpha)
    box = alpha.point(lambda v: 255 if v > 8 else 0).getbbox()
    return im.crop(box) if box else im


os.makedirs(DST, exist_ok=True)
have = []
for f in sorted(os.listdir(SRC)):
    stem, ext = os.path.splitext(f)
    if ext.lower() not in ('.jpg', '.jpeg', '.png', '.webp', '.avif'):
        continue
    cid = ALIASES.get(stem, re.sub(r'[^a-z0-9]', '', stem.lower()))
    if cid is None:
        continue
    im = cut_background(Image.open(os.path.join(SRC, f)))
    if cid in CROP_TOP:
        im = im.crop((0, 0, im.width, round(im.height * CROP_TOP[cid])))
        box = im.getchannel('A').point(lambda v: 255 if v > 8 else 0).getbbox()
        im = im.crop(box) if box else im
    if im.height > 1400:
        im = im.resize((round(im.width * 1400 / im.height), 1400), Image.LANCZOS)
    im.save(os.path.join(DST, cid + '.webp'), 'WEBP', quality=88, method=5)
    have.append(cid)
    print(f'{cid:12} {im.width}x{im.height}  ({f})')
for old in os.listdir(DST):
    if old.endswith('.webp') and old[:-5] not in have:
        os.remove(os.path.join(DST, old))
with open(os.path.join(DST, 'index.js'), 'w') as fh:
    fh.write('/* Generated by tools/femc-profiles.py: characters with full-body art (assets/femc/profile/<id>.webp). */\n')
    fh.write('window.FEMC_PROFILE = ' + json.dumps(sorted(have)) + ';\n')
