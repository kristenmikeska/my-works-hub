#!/usr/bin/env python3
"""Persona 3: Equinox's in-game stylesheets: blood-red copies of Solstice's (Kat, Nov 15 2026: Equinox is shades of red and
black; Solstice stays pink and black).

Reads every stylesheet femc-equinox-game.html uses from assets/femc/game/ and writes a copy to assets/femc/equinox/css/
with each pink / magenta / plum colour (hue 285-345 degrees, any lightness: the pinks, the pink-blacks, the paper tints)
turned to the same lightness on the red side (hue 354, a little more saturated). Gold, green, blue and the rarity colours
are left alone. Relative url(...) paths are rewritten so they still point at assets/femc/game/.

Run after any change to Solstice's game CSS, then bump the ?v= of the copies in femc-equinox-game.html:
    python3 tools/equinox-css.py
The copies are generated: never edit them by hand (Equinox-only rules go in assets/femc/equinox/game.css).
"""
import colorsys, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets/femc/game')
OUT = os.path.join(ROOT, 'assets/femc/equinox/css')
FILES = ['game.css', 'gacha.css', 'booth.css', 'echoes.css', 'solstice-ui.css', 'solstice-menu.css', 'solstice-hud.css',
         'solstice-links.css', 'solstice-pages.css', 'solstice-pages2.css', 'solstice-index.css', 'solstice-goout.css',
         'solstice-scene.css', 'solstice-life.css', 'gifts.css', 'fitting.css', 'boutique.css']
HUE_FROM, HUE_TO, RED = 285 / 360, 345 / 360, 354 / 360


# The Equilux palette (mockups/equinox-ui/equilux.html) for Solstice's main colours; anything else pink is hue-shifted.
EXACT = {'ff4f9e': 'd7102c', 'ff8cc0': 'ff5a5f', 'ffd6e8': 'f6d0d2', 'fff4f9': 'f6efe9', '14070f': '0a0304', '0c0309': '070203',
         '2a0f22': '2a0509', '4a1838': '4a0a12', 'a8326f': '8f0b1f', '7a0b3e': '6e0817', 'd9a9c0': 'c9a2a5', 'ffb3d4': 'ff9a9e',
         'b0185e': 'a00d24', '3a1028': '3a0710', '1b0b15': '1b0507', 'ffb3d6': 'ff9a9e'}


GREEN = False  # set per rule: inside Dark Hour rules the Dark Hour's green turns red too (Kat, Nov 15: Equinox's Dark Hour is red)
DH_SEL = re.compile(r'g-dh|gs-tint|darkhour|dark-hour|\.dh\b|g-hud\.dark|is-dark')


def shift(r, g, b):
    k = '%02x%02x%02x' % (r, g, b)
    if k in EXACT:
        v = EXACT[k]
        return tuple(int(v[i:i + 2], 16) for i in (0, 2, 4))
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    if GREEN and s >= 0.08 and 75 / 360 <= h <= 185 / 360:
        r2, g2, b2 = colorsys.hls_to_rgb(RED, l * 0.78, min(1.0, s * 1.1))
        return round(r2 * 255), round(g2 * 255), round(b2 * 255)
    if s < 0.08 or not (HUE_FROM <= h <= HUE_TO):
        return None
    s = min(1.0, s * 1.1)
    if 0.35 < l < 0.85:
        l *= 0.84  # Equilux reds sit darker than Solstice's pinks
    r2, g2, b2 = colorsys.hls_to_rgb(RED, l, s)
    return round(r2 * 255), round(g2 * 255), round(b2 * 255)


def hex_sub(m):
    t = m.group(1)
    full = ''.join(c * 2 for c in t) if len(t) in (3, 4) else t
    rgb = tuple(int(full[i:i + 2], 16) for i in (0, 2, 4))
    alpha = full[6:8] if len(full) == 8 else ''
    x = shift(*rgb)
    return m.group(0) if x is None else '#%02x%02x%02x%s' % (*x, alpha)


def rgb_sub(m):
    fn, a, b, c, rest = m.group(1), m.group(2), m.group(3), m.group(4), m.group(5)
    x = shift(int(a), int(b), int(c))
    return m.group(0) if x is None else f'{fn}({x[0]}, {x[1]}, {x[2]}{rest}'


def url_sub(m):
    q, u = m.group(1), m.group(2)
    if re.match(r'^(data:|https?:|/|#)', u):
        return m.group(0)
    return f'url({q}../../game/{u}{q})'


def colours(css):
    css = re.sub(r'#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})\b', hex_sub, css)
    css = re.sub(r'(rgba?)\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)(\s*[,)/])', rgb_sub, css)
    return css


def rule_sub(m):
    global GREEN
    GREEN = bool(DH_SEL.search(m.group(1)))
    out = m.group(1) + '{' + colours(m.group(2)) + '}'
    GREEN = False
    return out


def convert(css):
    css = re.sub(r'([^{}]*)\{([^{}]*)\}', rule_sub, css)  # innermost rules (the selector decides the Dark Hour greens)
    css = re.sub(r'url\(\s*([\'"]?)([^\'")]+)\1\s*\)', url_sub, css)
    return css


def main():
    os.makedirs(OUT, exist_ok=True)
    for f in FILES:
        src = open(os.path.join(SRC, f), encoding='utf-8').read()
        head = f'/* GENERATED by tools/equinox-css.py from assets/femc/game/{f} (blood-red copy for Persona 3: Equinox). Do not edit. */\n'
        open(os.path.join(OUT, f), 'w', encoding='utf-8').write(head + convert(src))
    print(f'{len(FILES)} stylesheets → {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    sys.exit(main())
