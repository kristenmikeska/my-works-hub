"""Normalizes Kat's FEMC portraits into the site: trimmed, same height, webp, plus a manifest of who has what."""
import os, re, json, glob
from PIL import Image
SRC = '/Users/katarinagrande/Documents/UniverseHub-Images/Femc Mode Images/Character Portraits'
DST = '/Users/katarinagrande/Desktop/Narrative Universe Sites/my-works-hub/assets/femc/portraits'
ALIAS = {'aki': 'akihiko'}
EMO = {'mad': 'serious', 'angry': 'serious', 'embarrassed': 'flustered'}
H = 860
manifest = {}
for folder in sorted(os.listdir(SRC)):
    path = os.path.join(SRC, folder)
    if not os.path.isdir(path): continue
    cid = folder.lower()
    for f in sorted(os.listdir(path)):
        stem, ext = os.path.splitext(f)
        if ext.lower() not in ('.png', '.webp', '.jpg', '.jpeg'): continue
        parts = stem.split('-', 1)
        if len(parts) < 2: continue
        rest = parts[1].lower()
        variant = ''
        m = re.match(r'(.+?)-(\d+)$', rest)
        if m: rest, variant = m.group(1), m.group(2)
        emotions = [EMO.get(x, x) for x in re.split(r'[:/_]', rest)]
        im = Image.open(os.path.join(path, f)).convert('RGBA')
        bbox = im.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
        if bbox: im = im.crop(bbox)
        if im.height != H:
            im = im.resize((round(im.width * H / im.height), H), Image.LANCZOS)
        os.makedirs(os.path.join(DST, cid), exist_ok=True)
        for emo in emotions:
            name = emo + (f'-{variant}' if variant and variant != '1' else '')
            im.save(os.path.join(DST, cid, name + '.webp'), 'WEBP', quality=86, method=6)
            manifest.setdefault(cid, []).append(name)
for k in manifest: manifest[k] = sorted(set(manifest[k]))
with open(os.path.join(DST, 'index.js'), 'w') as fh:
    fh.write('/* Generated by the portrait script: which expressions exist for each character (assets/femc/portraits/<id>/<emotion>.webp). */\n')
    fh.write('window.FEMC_PORTRAITS = ' + json.dumps(manifest, indent=1) + ';\n')
print(json.dumps(manifest))
