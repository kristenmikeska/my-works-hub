"""Echo art (Persona 3: Solstice, 2026-10-27): cuts Kat's Echo sheets into one picture per Echo and lists them for the game.

The game (assets/femc/battle/echoes.js art()) shows an Echo's own art as soon as its id is in
assets/femc/battle/art/echoes/index.js (FEMC_ECHO_ART); until then a stand-in Shadow or its arcana's tarot card.

Run:  python3 tools/femc-echoes.py cut SHEET.png id1,id2,id3,id4,id5,id6 [--grid 3x2] [--keep]
          Splits the sheet into a grid (6 → 3x2, 4 → 2x2, 5 → 3x2 with the last cell empty, 1 → the whole sheet), in reading
          order, cleans each cell with tools/femc-artclean.py one (cut-out, fringe cleanup, rim; same look as the Personas), writes
          assets/femc/battle/art/echoes/<id>.webp, then rewrites the index. --keep: keep the raw cells next to the output (.png).
      python3 tools/femc-echoes.py index     rewrite index.js from the files present (and bump FEMC_ECHO_ART_V)
      python3 tools/femc-echoes.py list      every Echo id, its sheet in FEMC-ART-TODO.md, and whether its art is in
Never writes to Kat's source folders; the sheet is only read. Record each sheet in tools/femc-new-adds.json after wiring."""
import os, re, sys, subprocess, tempfile
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
OUT = os.path.join(REPO, 'assets', 'femc', 'battle', 'art', 'echoes')
JS = os.path.join(REPO, 'assets', 'femc', 'battle', 'echoes.js')
INDEX = os.path.join(OUT, 'index.js')


def echo_ids():
    src = open(JS, encoding='utf-8').read()
    return re.findall(r"^\s*e\('([a-z0-9_]+)'", src, re.M)


def index():
    ids = set(echo_ids())
    have = sorted(f[:-5] for f in os.listdir(OUT) if f.endswith('.webp') and f[:-5] in ids)
    ver = 1
    if os.path.exists(INDEX):
        m = re.search(r'FEMC_ECHO_ART_V\s*=\s*(\d+)', open(INDEX).read())
        if m: ver = int(m.group(1)) + 1
    with open(INDEX, 'w') as f:
        f.write('/* Generated by tools/femc-echoes.py: Echoes whose own art is in (assets/femc/battle/art/echoes/<id>.webp).\n'
                '   Until an id is listed here, echoes.js shows its stand-in (a Shadow\'s art) or its arcana\'s tarot card. */\n')
        f.write('window.FEMC_ECHO_ART = [%s];\n' % ', '.join('"%s"' % i for i in have))
        f.write('window.FEMC_ECHO_ART_V = %d;\n' % ver)
    print(f'index: {len(have)} of {len(ids)} Echoes have art (v{ver})')


def grid_for(n, given=None):
    if given:
        c, r = given.lower().split('x'); return int(c), int(r)
    return {1: (1, 1), 2: (2, 1), 3: (3, 1), 4: (2, 2), 5: (3, 2), 6: (3, 2)}.get(n, (3, (n + 2) // 3))


def cut(sheet, ids, grid=None, keep=False):
    known = set(echo_ids())
    bad = [i for i in ids if i not in known]
    if bad: sys.exit(f'unknown Echo ids: {bad}')
    im = Image.open(sheet).convert('RGBA')
    cols, rows = grid_for(len(ids), grid)
    W, H = im.size
    cw, ch = W / cols, H / rows
    os.makedirs(OUT, exist_ok=True)
    for k, eid in enumerate(ids):
        c, r = k % cols, k // cols
        cell = im.crop((round(c * cw), round(r * ch), round((c + 1) * cw), round((r + 1) * ch)))
        with tempfile.TemporaryDirectory() as td:
            raw = os.path.join(td, f'{eid}.png')
            cell.save(raw)
            if keep: cell.save(os.path.join(OUT, f'{eid}.png'))
            dst = os.path.join(OUT, f'{eid}.webp')
            subprocess.run([sys.executable, os.path.join(HERE, 'femc-artclean.py'), 'one', raw, dst], check=True)
            print('wrote', os.path.relpath(dst, REPO))
    index()


def listing():
    have = set(f[:-5] for f in os.listdir(OUT) if f.endswith('.webp')) if os.path.isdir(OUT) else set()
    for i in echo_ids():
        print(f"{i:16} {'art in' if i in have else '-'}")


if __name__ == '__main__':
    a = sys.argv[1:]
    if not a or a[0] not in ('cut', 'index', 'list'):
        print(__doc__); sys.exit(1)
    if a[0] == 'index': index()
    elif a[0] == 'list': listing()
    else:
        if len(a) < 3: sys.exit('cut SHEET.png id1,id2,...')
        g = a[a.index('--grid') + 1] if '--grid' in a else None
        cut(a[1], [x for x in a[2].split(',') if x], g, '--keep' in a)
