"""SUgram history for the Runners epilogue phone (Nov 7 2026, Kat: "use some photos from the runners world SUgram").

  python3 tools/femc-sugram.py

Reads the Runners World site next to this repo (read only: runners-world/scripts/data/sugram-posts.js and
sugram-profiles.js, loaded with jsc) and takes its posts in story order up to and including CUT, the last post before the
epilogue's December (Halloween; the site's camping / Thanksgiving / winter-break / spring posts are left out: the epilogue
tells its own December). For each post: its picture(s) as WebP (longest side 720, q76) in
assets/femc/game/art/sugram/<post id>[-n].webp; each profile's picture (160 px square) as art/sugram/av/<handle>.webp.
Writes assets/femc/game/data/epi/runners/sugram-history.js (window.FEMC_SUGRAM_HISTORY = { profiles, posts }), oldest
first. A post id defined twice in the site's data keeps its first definition (as the site's own map does).
Re-run after the site's posts change; then bump sugram-history.js's ?v= in femc-game.html."""
import json, os, subprocess, sys, tempfile
from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RW = os.path.join(os.path.dirname(ROOT), 'runners-world')
OUT = os.path.join(ROOT, 'assets/femc/game/art/sugram')
DATA = os.path.join(ROOT, 'assets/femc/game/data/epi/runners/sugram-history.js')
JSC = '/System/Library/Frameworks/JavaScriptCore.framework/Versions/Current/Helpers/jsc'
CUT = 'jeno-late-fall-sigma-dump'
SIDE, Q, AV = 720, 76, 160
# Caption fixes for the game (the site is untouched): Runners canon makes Jaehyun the football captain and quarterback.
FIXES = {'su-arrival': [('SU soccer star', 'SU football star')]}

DUMP = r"""
const assets = (p) => `assets/${p}`;
load('scripts/data/sugram-posts.js');
load('scripts/data/sugram-profiles.js');
const byId = {}; socialPosts.forEach(p => { if (!byId[p.id]) byId[p.id] = p; });
const cut = storyOrder.indexOf('%s');
const posts = storyOrder.slice(0, cut + 1).map(id => byId[id]).filter(Boolean).map(p => ({ id: p.id, user: p.user,
  images: (p.images && p.images.length ? p.images : [p.image]).filter(Boolean), caption: p.caption || '', likes: p.likes || '',
  comments: p.comments || [], location: p.location || '' }));
const profiles = {}; Object.entries(socialProfiles).forEach(([h, p]) => { profiles[h] = { name: p.name || h, avatar: p.avatar, bio: p.bio || '' }; });
print(JSON.stringify({ posts, profiles }));
""" % CUT


def webp(src, dst, side=SIDE, square=False):
    im = ImageOps.exif_transpose(Image.open(src)).convert('RGB')
    if square:
        s = min(im.size); l, t = (im.width - s) // 2, (im.height - s) // 4
        im = im.crop((l, t, l + s, t + s)).resize((side, side), Image.LANCZOS)
    elif max(im.size) > side:
        im.thumbnail((side, side), Image.LANCZOS)
    im.save(dst, 'WEBP', quality=Q, method=5)


def main():
    with tempfile.NamedTemporaryFile('w', suffix='.js', delete=False) as f:
        f.write(DUMP); js = f.name
    raw = subprocess.run([JSC, js], cwd=RW, capture_output=True, text=True, check=True).stdout
    os.unlink(js)
    d = json.loads(raw)
    os.makedirs(os.path.join(OUT, 'av'), exist_ok=True)
    posts, missing = [], []
    for p in d['posts']:
        n = 0
        for k, rel in enumerate(p['images'][:6]):
            src = os.path.join(RW, rel)
            if not os.path.exists(src): missing.append(rel); continue
            dst = os.path.join(OUT, f"{p['id']}{'' if k == 0 else f'-{k}'}.webp")
            if not os.path.exists(dst): webp(src, dst)
            n += 1
        if not n: continue
        cap = p['caption']
        for a, b in FIXES.get(p['id'], []): cap = cap.replace(a, b)
        posts.append({'id': p['id'], 'user': p['user'], 'n': n, 'cap': cap, 'likes': p['likes'],
                      'comments': [c[:2] for c in p['comments'] if isinstance(c, list) and len(c) >= 2], 'loc': p['location']})
    users = {p['user'] for p in posts}
    profiles = {}
    for h, pr in d['profiles'].items():
        if h not in users: continue
        src = os.path.join(RW, pr['avatar'] or '')
        if pr['avatar'] and os.path.exists(src):
            webp(src, os.path.join(OUT, 'av', f'{h}.webp'), AV, square=True)
        profiles[h] = {'name': pr['name'], 'bio': pr['bio'], 'av': bool(pr['avatar'] and os.path.exists(src))}
    with open(DATA, 'w') as f:
        f.write('/* Generated by tools/femc-sugram.py from the Runners World site\'s SUgram (read only): its posts in story order up\n'
                f'   to {CUT} (Halloween), before the epilogue\'s December. Don\'t edit by hand: re-run the tool.\n'
                '   posts: { id, user (handle), n (pictures: art/sugram/<id>.webp, <id>-1.webp…), cap, likes, comments [[handle, text]], loc } */\n')
        f.write('window.FEMC_SUGRAM_HISTORY = ' + json.dumps({'profiles': profiles, 'posts': posts}, ensure_ascii=False, separators=(',', ':')) + ';\n')
    size = sum(os.path.getsize(os.path.join(OUT, x)) for x in os.listdir(OUT) if x.endswith('.webp'))
    print(f'{len(posts)} posts, {len(profiles)} profiles, {size / 1e6:.1f} MB of pictures; missing {len(missing)}', missing[:5])


if __name__ == '__main__':
    sys.exit(main())
