/* FEMC epilogue minigame: baduk (Nov 11 2026). Go capture puzzles (tsumego) at the board in the house, for the strangers epilogue
   (Incheon, Feb-Mar 2013). A DEMO: not in the story (try it at mockups/minigames/index.html once the card is added). Someone sits
   across the board and doesn't say much; the voice is never named and the puzzles carry no plot.

   FemcBaduk.play({ host, mute, difficulty, count, ids, hints, onDone }) -> Promise<result>
     host        element to draw into (default document.body; a full-screen overlay is added inside it)
     mute        no audio at all
     difficulty  'easy' | 'normal' | 'hard' (default 'normal'): easy 6 puzzles with hints and, after two misses on one, a ring on
                 the first move; normal 9 puzzles with hints; hard all 12, no hints (the voice only says "Again." and the like)
     count       play the first N puzzles of the whole list instead of the difficulty's set (1-12)
     ids         play exactly these puzzle ids, in this order (overrides count and the set)
     hints       true / false overrides the difficulty's hints
     onDone      called with the result too
   result = { won, grade: 'S' | 'A' | 'B' | 'C', puzzles, played, solved, firstTry, misses, skipped, quit, difficulty,
              results: [{ id, solved, first, misses, skipped }] }
     won = not quit and at least two thirds solved. Grade by first-try solves over the whole set (unplayed ones count as missed
     when you quit): S 90%+ with nothing passed, A 70%+, B 45%+, else C. Quitting (Esc → Quit) ends with the partial grade.

   How it plays: one puzzle at a time on a 9x9 board, always Black to play, a goal under the title (capture, live, kill, win the
   race). Click / tap a point (touch: tap shows the stone, tap again places it; keys: arrows + Enter / Space). The engine plays
   real Go: captures, liberties, no suicide, simple ko. White answers from the puzzle's solution tree. A correct move gets White's
   most stubborn reply and the line goes on; a wrong move gets the refutation, a quiet line from across the board (the puzzle's
   hint with hints on, a dry "Again." without), and Again resets the puzzle. Pass skips it (counts unsolved). Captured stones lift
   off into the lids beside the board (Taken / Lost). The voice: "Count the liberties.", "That one breathes.", "Again."
   Title card: art/minigames/baduk/title.webp if present (a drawn board with a banana laid neatly on it otherwise), held 1.8 s,
   click / a key skips. Board: art/minigames/baduk/board.webp under the grid if present, else drawn wood. Stones are always drawn.
   Sounds (Web Audio, made here, no files; mute = silent): a wooden clack per stone, a soft lift and a clatter in the lid per
   capture, a low two-note on a miss, a small chime on a solve. Esc pauses (Resume / Quit). Reduced motion: no drop or lift,
   stones fade into the lids. Pink and black chrome only; the board is wood and stones.

   Puzzle format (PUZZLES below; their trees in TREES):
     { id, title, lesson, text, board: [9 strings, 'X' black 'O' white '.' empty, top row first], goal, plies, area, moves,
       hints: [after the 1st miss, after the 2nd+], done }
     goal  { type: 'capture', stones: [sgf], any } the listed white stones captured (any: one of them is enough)
           { type: 'race', stones, mine }       the white stones captured before any of `mine` (black) are
           { type: 'live', stones }             the black group made unconditionally alive (Benson)
           { type: 'kill', stones }             the white group can no longer live (proved by the test's solver)
     plies the length the solver checks a line to (the puzzle is "solve it in this many moves"); area = 'xy-xy' (sgf corners),
           the points the solver tries; moves = black moves shown before the tree stops (kill / live lines)
     Points are SGF letters: 'aa' top-left, first letter the column, second the row ('ei' = column e, bottom row).
   Tree (TREES[id]) = a black-to-move node: { ok: { move: child | 0 }, no: { move: reply }, else: [reply, ...] }
     ok    correct moves; 0 = solved right there, else child = { w: White's reply, ...the next black node }
     no    a wrong move with its own refutation; any other legal move is wrong too and gets the first legal move in `else`
           (no legal one: White passes). 'pass' is a legal reply.
   The trees were generated by a small solver (search over `area`, `plies` deep) and checked by a jsc stub test (a scratch
   harness, not in the repo; sound mode: White may answer anywhere in the area, no shortcuts): every correct move wins against
   every defence, every wrong move's in-game reply refutes it (moves outside the area too), and no other move wins, so a
   "wrong" answer never secretly works. Several puzzles accept more than one correct move (the ladder can also be laddered the
   other way or netted; the corner lives two ways). FemcBaduk.check() replays every authored line and reports problems.
   Tutorial (Nov 11 2026, Kat: every minigame teaches itself first): after the title card, the first time only (FemcTutorial seen-state
   'baduk'), Appa (lee-appa's face; in the story he's the one across the board) walks a staged practice position on the real board,
   before puzzle 1 loads: Black to play, put a stone on the ring, liberties (the white stone's last one marked), take it on the dot
   (it lifts into the lid), play a wrong move on purpose and see his answer, press Again, and where Pass is. Nothing counts: the lids
   and pips are put back and puzzle 1 loads fresh. play({ tutorial: true | false }) forces / skips it (the story passes neither).
   Esc → Pause → How to play replays it over the paused puzzle (its position is saved and put back after; Next on every step).
   result.tutorial = 'done' | 'skipped' | 'seen' (not shown). Helper: minigames/tutorial.js (FemcTutorial), loaded on demand.
   state().prac is the practice while it's up ({ ring, lib } as points; place(p) plays like a click). */
