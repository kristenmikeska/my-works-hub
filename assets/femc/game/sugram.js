/* SUgram, the Runners epilogue phone's third app (Nov 7 2026, Kat: "i would love a little SUgram app on the phone",
   comments too, photos from the Runners World SUgram).
   Data: the world's R.sugram (data/epi/runners/sugram.js: this December's posts and their comments) and
   window.FEMC_SUGRAM_HISTORY (sugram-history.js, generated by tools/femc-sugram.py: the site's posts up to Halloween,
   pictures in art/sugram/). A world without R.sugram has no app (has()).
   What shows: every history post (the fall, "Earlier this fall"), and this December's posts once Solar has seen them: a
   post line from a scene (S.album.posts) or an alert that dropped in (S.epi.alerts). log(id) (ui.js seePost, epilogue.js
   newsTick) keeps the day each arrived in S.epi.gram, newest first; anything seen before the log existed sits under the
   logged ones. S.epi.gramSeen = how many December posts were in the feed when it was last opened (the tab's dot).
   Hearts: S.epi.gramLiked { key: 1 } (adds one to the count; looks only, nothing else reads it).
   Views (inside the phone's body; ui.js openPhone passes its pieces): feed → a profile (tap a handle or picture) → one post
   (tap a grid tile); the phone's ‹ steps back (back(): true while it had somewhere to go). No story state is touched. */
(() => {
  const G = () => window.FemcGame;
  const S = () => G().S;
  const esc = s => String(s == null ? '' : s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  const R = () => ((window.FEMC_EPI_WORLDS || {})[G().world?.() || ''] || {}).sugram || null;
  const H = () => window.FEMC_SUGRAM_HISTORY || { profiles: {}, posts: [] };
  const base = () => G().base || '';
  const has = () => !!(S().epi && R());
  const PAGE = 12;

  /* ── State ── */
  function log(id) {
    const s = S(), r = R();
    if (!s.epi || !r || !r.posts[id]) return;
    const g = s.epi.gram ||= [];
    if (!g.some(x => x.id === id)) g.push({ id, day: s.day });
  }
  // The December posts in the feed: logged ones newest first, then any seen before the log existed.
  function live() {
    const s = S(), r = R(); if (!r) return [];
    const g = (s.epi.gram || []).filter(x => r.posts[x.id]);
    const ids = g.map(x => x.id);
    const seen = [...(s.epi.alerts || []), ...((s.album || {}).posts || [])].filter(id => r.posts[id] && !ids.includes(id));
    return [...g.slice().reverse(), ...seen.map(id => ({ id, day: null }))];
  }
  const unread = () => has() ? Math.max(0, live().length - (S().epi.gramSeen || 0)) : 0;

  /* ── Post records: one shape for both sources ── */
  const ALERTS = () => (((window.FEMC_EPI_WORLDS || {})[G().world?.() || ''] || {}).alerts || []);
  const NEWS = { sunews: 'SUnews', suanon: 'SUanon' };
  function liveRec(x) {
    const p = R().posts[x.id], a = ALERTS().find(z => z.id === x.id);
    const img = p.img || (a && a.img);
    const pics = img && (window.FEMC_POSTS || []).includes(img) ? [`${base()}assets/femc/game/art/posts/${img}.webp?v=${window.FEMC_POSTS_V || 1}`] : [];
    return { key: x.id, user: p.user || (a && NEWS[a.from]) || 'SUnews', cap: p.cap != null ? p.cap : (a ? a.t : ''), likes: p.likes || '', comments: p.comments || [], pics, when: whenOf(x.day), live: true };
  }
  function histRec(p) {
    const pics = Array.from({ length: p.n }, (_, k) => `${base()}assets/femc/game/art/sugram/${p.id}${k ? `-${k}` : ''}.webp`);
    return { key: 'h:' + p.id, user: p.user, cap: p.cap, likes: p.likes, comments: p.comments || [], pics, when: p.loc || 'Syracuse University', live: false };
  }
  function whenOf(day) {
    if (day == null) return 'December';
    const d = S().day - day;
    return d <= 0 ? 'Today' : d === 1 ? 'Yesterday' : `${d} days ago`;
  }
  const feed = () => [...live().map(liveRec), ...H().posts.slice().reverse().map(histRec)];
  const byKey = k => feed().find(p => p.key === k);

  /* ── Pieces ── */
  const nameOf = h => (H().profiles[h] || {}).name || (R().names || {})[h] || h;
  function avatar(h) {
    const hp = H().profiles[h];
    if (hp && hp.av) return `<img src="${base()}assets/femc/game/art/sugram/av/${esc(h)}.webp" alt="">`;
    const own = (R().avatars || {})[h], world = G().world?.(), list = ((window.FEMC_AVATARS || {})[world] || []);
    if (own && list.includes(own)) return `<img src="${base()}assets/femc/game/art/avatars/${world}/${own}.webp?v=${window.FEMC_AVATARS_V || 1}" alt="">`;
    return `<span>${h === 'SUanon' ? '?' : esc((h || '?').replace(/^[^a-z0-9]+/i, '')[0] || '?')}</span>`;
  }
  const liked = k => !!(S().epi.gramLiked || {})[k];
  const likeCount = p => {
    const n = parseInt(String(p.likes).replace(/[^0-9]/g, ''), 10);
    if (!n && !liked(p.key)) return '';
    return ((n || 0) + (liked(p.key) ? 1 : 0)).toLocaleString('en-US');
  };
  function postHtml(p, open) {
    const pics = p.pics.length
      ? `<div class="g-sg-pics${p.pics.length > 1 ? ' many' : ''}">${p.pics.map((src, i) => `<img src="${src}" alt="" loading="lazy" decoding="async"${i ? ' aria-hidden="true"' : ''}>`).join('')}</div>${p.pics.length > 1 ? `<small class="g-sg-count">1 / ${p.pics.length} · swipe</small>` : ''}`
      : `<div class="g-sg-text"><p>${esc(p.cap)}</p></div>`;
    const cs = p.comments, shown = open ? cs : cs.slice(0, 2);
    const likes = likeCount(p);
    return `<article class="g-sg-post" data-sg-post="${esc(p.key)}">
      <header><button type="button" class="g-sg-who" data-sg-user="${esc(p.user)}"><i class="g-sg-av">${avatar(p.user)}</i><span><b>${esc(p.user)}</b><small>${esc(p.when)}</small></span></button></header>
      ${pics}
      <div class="g-sg-acts"><button type="button" class="g-sg-heart${liked(p.key) ? ' on' : ''}" data-sg-like="${esc(p.key)}" aria-pressed="${liked(p.key)}" aria-label="Like">${liked(p.key) ? '♥' : '♡'}</button>${likes ? `<b>${likes} likes</b>` : ''}</div>
      ${p.cap && p.pics.length ? `<p class="g-sg-cap"><b>${esc(p.user)}</b> ${esc(p.cap)}</p>` : ''}
      ${shown.length ? `<ul class="g-sg-cms">${shown.map(([h, t]) => `<li><button type="button" class="g-sg-cmu" data-sg-user="${esc(h)}">${esc(h)}</button> ${esc(t)}</li>`).join('')}</ul>` : ''}
      ${!open && cs.length > 2 ? `<button type="button" class="g-sg-more" data-sg-open="${esc(p.key)}">View all ${cs.length} comments</button>` : ''}
    </article>`;
  }

  /* ── Views ── */
  let stack = [], shownN = PAGE, ctx = null;
  function render() {
    const c = ctx, v = stack[stack.length - 1] || { kind: 'feed' };
    c.title.textContent = v.kind === 'feed' ? 'SUgram' : v.kind === 'user' ? v.user : 'Post';
    c.title.dataset.gram = '1';
    c.back.hidden = v.kind === 'feed';
    let html = '';
    if (v.kind === 'feed') {
      const L = live().map(liveRec), hist = H().posts.slice().reverse().map(histRec);
      S().epi.gramSeen = live().length; G().saveQuiet?.();
      html = c.tabsHtml() + `<div class="g-sg">`
        + (L.length ? L.map(p => postHtml(p)).join('') : `<p class="g-sg-lede">Nothing new since you got back. Give it a day.</p>`)
        + (hist.length ? `<h3 class="g-sg-sep">Earlier this fall</h3>` + hist.slice(0, shownN).map(p => postHtml(p)).join('')
          + (hist.length > shownN ? `<button type="button" class="g-sg-load" data-sg-load>Show more</button>` : '') : '')
        + `</div>`;
    } else if (v.kind === 'user') {
      const posts = feed().filter(p => p.user === v.user), hp = H().profiles[v.user] || {};
      html = `<div class="g-sg g-sg-prof"><header class="g-sg-ph"><i class="g-sg-av big">${avatar(v.user)}</i><div><b>${esc(nameOf(v.user))}</b><small>@${esc(v.user)} · ${posts.length} posts</small>${hp.bio ? `<p>${esc(hp.bio)}</p>` : ''}</div></header>`
        + (posts.length ? `<div class="g-sg-grid">${posts.map(p => `<button type="button" data-sg-open="${esc(p.key)}" aria-label="Open post">${p.pics.length ? `<img src="${p.pics[0]}" alt="" loading="lazy" decoding="async">` : `<span>${esc(p.cap.slice(0, 60))}</span>`}</button>`).join('')}</div>`
          : `<p class="g-sg-lede">No posts yet.</p>`) + `</div>`;
    } else {
      const p = byKey(v.key);
      html = `<div class="g-sg">${p ? postHtml(p, true) : ''}</div>`;
    }
    c.body.innerHTML = html;
    c.wireTabs();
    wire();
  }
  function go(v) { stack.push(v); render(); ctx.body.scrollTop = 0; }
  function wire() {
    const b = ctx.body;
    b.querySelectorAll('[data-sg-user]').forEach(el => el.addEventListener('click', () => { G().sfx?.('femc-click'); go({ kind: 'user', user: el.dataset.sgUser }); }));
    b.querySelectorAll('[data-sg-open]').forEach(el => el.addEventListener('click', () => { G().sfx?.('femc-click'); go({ kind: 'post', key: el.dataset.sgOpen }); }));
    b.querySelectorAll('[data-sg-like]').forEach(el => el.addEventListener('click', () => {
      const s = S(), L = s.epi.gramLiked ||= {}, k = el.dataset.sgLike;
      if (L[k]) delete L[k]; else L[k] = 1;
      G().saveQuiet?.(); G().sfx?.('femc-click');
      const p = byKey(k); if (!p) return;
      const art = el.closest('.g-sg-post'), keep = ctx.body.scrollTop;
      art.outerHTML = postHtml(p, (stack[stack.length - 1] || {}).kind === 'post');
      ctx.body.scrollTop = keep; wire();
    }));
    const more = b.querySelector('[data-sg-load]');
    if (more) more.addEventListener('click', () => { const keep = b.scrollTop; shownN += PAGE; render(); b.scrollTop = keep; });
    b.querySelectorAll('.g-sg-pics.many').forEach(box => box.addEventListener('scroll', () => {
      const i = Math.round(box.scrollLeft / box.clientWidth), n = box.children.length, lab = box.nextElementSibling;
      if (lab && lab.classList.contains('g-sg-count')) lab.textContent = `${i + 1} / ${n}`;
    }, { passive: true }));
  }
  // ui.js: open the app (ctx = { body, title, back, tabsHtml, wireTabs }); opts.post opens one post on top of the feed.
  function open(c, opts = {}) {
    ctx = c; stack = []; shownN = PAGE;
    render();
    if (opts.post && byKey(opts.post)) go({ kind: 'post', key: opts.post });
  }
  function back() {
    if (!ctx || stack.length === 0) return false;
    stack.pop(); render(); return true;
  }
  window.FemcSugram = { has, log, live, unread, open, back, feed };
})();
